type SameKeys<Left, Right> = Exclude<keyof Left, keyof Right> extends never
  ? Exclude<keyof Right, keyof Left> extends never
    ? true
    : false
  : false;
type Assert<T extends true> = T;
export type MessageDictionaryKeysAreAligned = Assert<SameKeys<typeof messages.ar, typeof messages.en>>;

export type Language = keyof typeof messages;
export type MessageKey = keyof typeof messages.ar;

type TranslationParams = Readonly<Record<string, string | number>>;

export function t(lang: Language, key: MessageKey, params?: TranslationParams): string {
  let value: string = messages[lang][key];
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function getLang(cookieHeaderOrValue?: string | null): Language {
  if (!cookieHeaderOrValue) return "ar";
  const value = cookieHeaderOrValue.split(";").map((part) => part.trim()).find((part) => part.startsWith("rabto_lang="));
  return value?.slice("rabto_lang=".length) === "en" || cookieHeaderOrValue === "en" ? "en" : "ar";
}
